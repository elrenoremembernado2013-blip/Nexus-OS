#!/usr/bin/env node
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const source = fs.readFileSync("apps/window-manager.js", "utf8");
const sandbox = { window: {} };
vm.runInNewContext(source, sandbox, { filename: "apps/window-manager.js" });
const manager = sandbox.window.NexusWindowManager;
assert.ok(manager);

const events = [];
const unsub = manager.subscribe(event => events.push(event.type + (event.window ? ":" + event.window.id : "")));
let closed = 0;
const first = manager.open("notes", "Notes", { onClose: () => closed++ });
const second = manager.open("notes", "Notes — second instance");
const third = manager.open("calendar", "Calendar");
assert.notEqual(first, second);
assert.notEqual(second, third);
assert.equal(manager.list().length, 3);
assert.equal(manager.getActive().id, third);
assert.equal(manager.setTitle(second, "Notes renamed"), true);
assert.equal(manager.get(second).title, "Notes renamed");
assert.equal(manager.focus(first), true);
assert.equal(manager.getActive().id, first);
assert.equal(manager.minimize(first), true);
assert.notEqual(manager.getActive()?.id, first);
assert.equal(manager.get(first).state, "minimized");
assert.equal(manager.restore(first), true);
assert.equal(manager.getActive().id, first);
assert.equal(manager.close(first), true);
assert.equal(closed, 1);
assert.equal(manager.get(first), null);
assert.equal(manager.close(first), false);
assert.equal(manager.minimizeApp("notes"), 0, "only normal notes windows minimize");
assert.equal(manager.restore(second), true);
assert.equal(manager.minimizeApp("notes"), 1);
assert.equal(manager.restore(second), true);
assert.equal(manager.closeApp("notes"), 1);
assert.equal(manager.list().length, 1);
assert.equal(manager.closeApp("missing"), 0);
assert.equal(manager.close(third), true);
assert.equal(manager.getActive(), null);
assert.equal(manager.focus("missing"), false);
assert.equal(manager.minimize("missing"), false);
assert.equal(manager.restore("missing"), false);
assert.throws(() => manager.open("invalid app", "Bad"), /valid app ID/);
unsub();
manager.open("notes", "after unsubscribe");
assert.ok(!events.some(e => e.startsWith("open:nexus-window-4")));
console.log("PASS NEXUS window manager core tests");
